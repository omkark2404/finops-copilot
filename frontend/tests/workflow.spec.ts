import {test,expect} from './fixtures'
import path from 'node:path'
test('reload, upload, switch dataset, inspect, save review, simulate and delete',async({page,context})=>{
  test.setTimeout(120000)
  const errors:string[]=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/login')
  await expect(page.getByRole('button',{name:'Sign in',exact:true})).toBeEnabled()
  await page.getByLabel('Email',{exact:true}).fill('browser@test.local')
  await expect(page.getByLabel('Email',{exact:true})).toHaveValue('browser@test.local')
  await page.getByLabel('Password',{exact:true}).fill('browser-test-password-123')
  await expect(page.getByLabel('Password',{exact:true})).toHaveValue('browser-test-password-123')
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await expect(page).toHaveURL(/dashboard/)
  await expect(page.getByRole('heading',{name:'Overview'})).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading',{name:'Overview'})).toBeVisible()
  // This fixture is synthetic and intentionally labeled. It is not a predictive benchmark.
  const rows=['BilledCost,EffectiveCost,ChargePeriodStart,ChargePeriodEnd,BillingCurrency,ServiceName,ProviderName']
  for(let day=0;day<40;day++){
    const start=new Date(Date.UTC(2024,0,day+1)).toISOString()
    const end=new Date(Date.UTC(2024,0,day+2)).toISOString()
    rows.push([day===30?800:100,100,start,end,'USD','Compute','FixtureCloud'].join(','))
  }
  await page.getByRole('link',{name:'Settings',exact:true}).click()
  await page.getByLabel('Dataset Name',{exact:true}).fill('SYNTHETIC TEST FIXTURE')
  await page.getByLabel('Billing File (CSV / Parquet)',{exact:true}).setInputFiles({name:'synthetic-fixture.csv',mimeType:'text/csv',buffer:Buffer.from(rows.join('\n'))})
  await page.getByRole('button',{name:'Ingest Dataset',exact:true}).click()
  await expect(page.getByText(/ingested successfully/)).toBeVisible()
  await page.getByRole('link',{name:'Overview',exact:true}).click()
  await expect(page.getByText('$4,700.00',{exact:true})).toBeVisible()
  await page.screenshot({path:path.resolve('../docs/images/dashboard.png'),fullPage:true})
  await page.getByRole('link',{name:'Spend Explorer',exact:true}).click()
  await expect(page.getByText('By service',{exact:true})).toBeVisible()
  await page.getByRole('link',{name:'Settings',exact:true}).click()
  await page.getByLabel('Dataset Name',{exact:true}).fill('SECOND SYNTHETIC TEST FIXTURE')
  const second=rows.map(row=>row.replace(/^800,/, '100,'))
  await page.getByLabel('Billing File (CSV / Parquet)',{exact:true}).setInputFiles({name:'second-synthetic.csv',mimeType:'text/csv',buffer:Buffer.from(second.join('\n'))})
  await page.getByRole('button',{name:'Ingest Dataset',exact:true}).click()
  await expect(page.getByText(/ingested successfully/)).toBeVisible()
  await page.getByRole('link',{name:'Overview',exact:true}).click()
  await expect(page.getByText('$4,000.00',{exact:true}).first()).toBeVisible()
  await page.getByRole('combobox',{name:'Active billing dataset'}).selectOption({label:'SYNTHETIC TEST FIXTURE (40 rows)'})
  await expect(page.getByText('$4,700.00',{exact:true})).toBeVisible()
  await page.setViewportSize({width:390,height:844})
  await expect(page.getByRole('link',{name:'Overview',exact:true})).toBeVisible()
  await page.screenshot({path:path.resolve('../docs/images/mobile.png'),fullPage:true})
  const overflow=await page.evaluate(()=>({width:window.innerWidth,scroll:document.documentElement.scrollWidth,elements:Array.from(document.querySelectorAll('body *')).filter(e=>e.getBoundingClientRect().right>window.innerWidth).slice(0,8).map(e=>({tag:e.tagName,cls:e.className}))}))
  expect(overflow.scroll,JSON.stringify(overflow)).toBeLessThanOrEqual(overflow.width)
  await page.setViewportSize({width:1280,height:720})
  await page.getByRole('link',{name:'Analysis Runs',exact:true}).click()
  await page.getByRole('button',{name:'Run Pipeline',exact:true}).click()
  await expect(page.getByText('Checklist outcome (human review required)',{exact:true})).toBeVisible()
  await page.getByRole('link',{name:'Recommendations',exact:true}).click()
  await expect(page.getByRole('button',{name:'Record approval'}).first()).toBeVisible()
  await page.getByRole('button',{name:'Record approval'}).first().click()
  await expect(page.getByText('approved',{exact:true}).first()).toBeVisible()
  await page.getByText('Hypothetical whole-dataset scenario',{exact:true}).first().click()
  await page.getByLabel('Assumed usage reduction (%)').first().fill('10')
  await page.getByRole('button',{name:'Simulate scenario',exact:true}).first().click()
  await expect(page.getByText('Estimated difference: $470.00',{exact:true})).toBeVisible()
  await page.getByRole('link',{name:'Settings',exact:true}).click()
  await page.getByRole('row').filter({has:page.getByRole('cell',{name:'SYNTHETIC TEST FIXTURE',exact:true})}).getByRole('button',{name:'Delete',exact:true}).click()
  await page.getByRole('button',{name:'Permanently delete',exact:true}).click()
  await expect(page.getByText(/was permanently deleted/)).toBeVisible()
  await page.getByRole('button',{name:'Delete',exact:true}).first().click()
  await page.getByRole('button',{name:'Permanently delete',exact:true}).click()
  await expect(page.getByText('No datasets ingested yet')).toBeVisible()
  expect(errors).toEqual([])
  await context.clearCookies()
})
